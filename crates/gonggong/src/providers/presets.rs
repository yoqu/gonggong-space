//! Vendor presets: the bundled `presets/providers.json` and the platform plugins' overlay over it.
use crate::protocol::{AgentKind, ApiProtocol};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;
use std::sync::{OnceLock, RwLock};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum PresetGroup {
    Cn,
    Aggregator,
    Global,
}

/// Claude Code's haiku/sonnet/opus aliases (`ANTHROPIC_DEFAULT_*_MODEL`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ModelMap {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub haiku: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sonnet: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub opus: Option<String>,
}

/// What a vendor serves on one protocol.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PresetEndpoint {
    pub protocol: ApiProtocol,
    pub base_url: String,
    #[serde(default)]
    pub api_key_field: Option<String>,
    #[serde(default)]
    pub wire_api: Option<String>,
    #[serde(default)]
    pub model: Option<String>,
    #[serde(default)]
    pub models: Option<ModelMap>,
    #[serde(default)]
    pub model_options: Vec<String>,
    #[serde(default)]
    pub env: BTreeMap<String, String>,
    #[serde(default)]
    pub effort: Option<String>,
    /// Claude: context window per model id, filled in unless the provider sets `CLAUDE_CODE_MAX_CONTEXT_TOKENS`.
    #[serde(default)]
    pub model_context: BTreeMap<String, u64>,
}

/// A built-in vendor from `presets/providers.json` (generated by `scripts/sync-provider-presets.mjs`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Preset {
    pub id: String,
    pub name: String,
    pub group: PresetGroup,
    #[serde(default)]
    pub website_url: Option<String>,
    #[serde(default)]
    pub api_key_url: Option<String>,
    pub endpoints: Vec<PresetEndpoint>,
}

impl Preset {
    pub fn endpoint(&self, protocol: ApiProtocol) -> Option<&PresetEndpoint> {
        self.endpoints.iter().find(|e| e.protocol == protocol)
    }
}

#[derive(Deserialize)]
struct PresetFile {
    source: String,
    presets: Vec<Preset>,
}

fn preset_file() -> &'static PresetFile {
    static FILE: OnceLock<PresetFile> = OnceLock::new();
    FILE.get_or_init(|| {
        serde_json::from_str(include_str!("../../presets/providers.json")).expect("bundled presets/providers.json")
    })
}

/// e.g. `cc-switch@36d9504`.
pub fn presets_source() -> &'static str {
    &preset_file().source
}

/// Presets of platform plugins (plan 插件扩展点 §6), kept in `<home>/presets-overlay.json` for the CLI and restarts.
pub(super) static OVERLAY: RwLock<Vec<Preset>> = RwLock::new(vec![]);
pub(super) const OVERLAY_FILE: &str = "presets-overlay.json";

/// Built-in presets with the overlay over them: the same id replaces a built-in in place, new ones follow.
pub(super) fn merged(builtin: &[Preset], overlay: &[Preset]) -> Vec<Preset> {
    let mut out: Vec<Preset> =
        builtin.iter().map(|b| overlay.iter().find(|o| o.id == b.id).unwrap_or(b).clone()).collect();
    out.extend(overlay.iter().filter(|o| !builtin.iter().any(|b| b.id == o.id)).cloned());
    out
}

/// Every vendor, or those serving a protocol `agent` takes.
pub fn presets(agent: Option<AgentKind>) -> Vec<Preset> {
    let overlay = OVERLAY.read().unwrap_or_else(|e| e.into_inner());
    let serves = |p: &Preset| agent.is_none_or(|a| p.endpoints.iter().any(|e| a.takes(e.protocol)));
    merged(&preset_file().presets, &overlay).into_iter().filter(serves).collect()
}

pub fn preset(id: &str) -> Option<Preset> {
    presets(None).into_iter().find(|p| p.id == id)
}

/// Reads the overlay the server last sent; a missing or unreadable file leaves only the built-in presets.
pub fn load_overlay(home: &Path) {
    let read = std::fs::read(home.join(OVERLAY_FILE)).ok().and_then(|b| serde_json::from_slice(&b).ok());
    *OVERLAY.write().unwrap_or_else(|e| e.into_inner()) = read.unwrap_or_default();
}

/// Replaces the overlay (`presets.sync`); an empty list clears it.
pub fn set_overlay(home: &Path, presets: Vec<Preset>) -> std::io::Result<()> {
    let file = home.join(OVERLAY_FILE);
    if presets.is_empty() {
        match std::fs::remove_file(&file) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => return Err(e),
            _ => {}
        }
    } else {
        std::fs::create_dir_all(home)?;
        std::fs::write(&file, serde_json::to_vec(&presets).expect("presets serialize"))?;
    }
    *OVERLAY.write().unwrap_or_else(|e| e.into_inner()) = presets;
    Ok(())
}
