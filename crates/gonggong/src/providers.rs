#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Provider {
    pub id: String,
    pub agent: AgentKind,
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub preset_id: Option<String>,
    /// Bumped on every change so running adapters can tell they must restart.
    pub revision: u32,
    pub base_url: String,
    pub api_key: String,
    /// Claude only: which variable carries the key ([`AUTH_TOKEN`] or [`API_KEY`]).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub api_key_field: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub models: Option<ModelMap>,
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub env: BTreeMap<String, String>,
    /// `http(s)://[user:pass@]host:port` the agent reaches the provider through; `None` = direct.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub proxy: Option<String>,
    /// Codex only.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub wire_api: Option<String>,
    /// Codex only: `model_reasoning_effort`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub effort: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<Source>,
}

impl Provider {
    /// A new provider (no id yet) copying the preset's values; later preset updates never touch it.
    pub fn from_preset(preset: &Preset, api_key: String) -> Provider {
        Provider {
            name: preset.name.clone(),
            preset_id: Some(preset.id.clone()),
            model: preset.model.clone(),
            models: preset.models.clone(),
            env: preset.env.clone(),
            api_key_field: preset.api_key_field.clone(),
            wire_api: preset.wire_api.clone(),
            effort: preset.effort.clone(),
            ..Provider::custom(preset.agent, preset.name.clone(), preset.base_url.clone(), api_key)
        }
    }

    pub fn custom(agent: AgentKind, name: String, base_url: String, api_key: String) -> Provider {
        Provider {
            id: String::new(),
            agent,
            name,
            preset_id: None,
            revision: 0,
            base_url,
            api_key,
            api_key_field: (agent == AgentKind::Claude).then(|| AUTH_TOKEN.into()),
            model: None,
            models: None,
            env: BTreeMap::new(),
            proxy: None,
            wire_api: (agent == AgentKind::Codex).then(|| WIRE_RESPONSES.into()),
            effort: None,
            source: None,
        }
    }

    fn validate(&self) -> Result<()> {
        if self.name.trim().is_empty() {
            bail!(t!("供应商名称不能为空"));
        }
        if !(self.base_url.starts_with("https://") || self.base_url.starts_with("http://")) {
            bail!(t!("Base URL 必须以 http:// 或 https:// 开头"));
        }
        if self.api_key.trim().is_empty() {
            bail!(t!("API Key 不能为空"));
        }
        validate_extras(&self.env, self.proxy.as_deref())
    }

    pub fn process_env(&self) -> BTreeMap<String, String> {
        process_env(&self.env, self.proxy.as_deref())
    }

    fn same_connection(&self, other: &Provider) -> bool {
        self.agent == other.agent
            && self.base_url.trim_end_matches('/') == other.base_url.trim_end_matches('/')
            && self.api_key == other.api_key
    }

    pub fn view(&self) -> ProviderView {
        ProviderView {
            id: self.id.clone(),
            agent: self.agent,
            name: self.name.clone(),
            preset_id: self.preset_id.clone(),
            revision: self.revision,
            base_url: self.base_url.clone(),
            api_key: mask_key(&self.api_key),
            api_key_field: self.api_key_field.clone(),
            model: self.model.clone(),
            models: self.models.clone(),
            env: self.env.clone(),
            proxy: self.proxy.as_deref().map(mask_proxy),
            wire_api: self.wire_api.clone(),
            effort: self.effort.clone(),
            source: self.source.clone(),
        }
    }
}

/// The agent process's env as if exported in a terminal: the proxy (both cases, loopback direct so the agent still
/// reaches the daemon's local MCP endpoint), then the user's own variables.
fn process_env(vars: &BTreeMap<String, String>, proxy: Option<&str>) -> BTreeMap<String, String> {
    let mut env = vars.clone();
    if let Some(url) = proxy {
        for k in ["HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"] {
            env.entry(k.into()).or_insert_with(|| url.into());
        }
        let user = vars.get("NO_PROXY").or(vars.get("no_proxy"));
        let bypass = ["localhost", "127.0.0.1", "::1"].into_iter().chain(user.map(String::as_str)).collect::<Vec<_>>();
        env.insert("NO_PROXY".into(), bypass.join(","));
        env.insert("no_proxy".into(), bypass.join(","));
    }
    env
}

fn validate_extras(env: &BTreeMap<String, String>, proxy: Option<&str>) -> Result<()> {
    if let Some(k) = env.keys().find(|k| !env_name(k)) {
        bail!(t!("环境变量名不合法：{name}", name = k));
    }
    if proxy.is_some_and(|u| !(u.starts_with("http://") || u.starts_with("https://"))) {
        bail!(t!("代理地址必须以 http:// 或 https:// 开头"));
    }
    Ok(())
}

